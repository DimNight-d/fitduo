const RECIPES_VERSION = 4;

// Підсумки по страві для базової порції
RECIPES.forEach(r => {
  let k = 0, p = 0, f = 0, c = 0;
  r.exp = false;
  r.tags = new Set();
  r.ing.forEach(([id, g]) => {
    const fd = FOODS[id];
    if (!fd) throw new Error('Невідомий продукт ' + id);
    k += fd.k * g / 100; p += fd.p * g / 100; f += fd.f * g / 100; c += fd.c * g / 100;
    (fd.tags || []).forEach(t => r.tags.add(t));
    if (fd.exp && g >= 30) r.exp = true;
  });
  Object.assign(r, { kcal: k, prot: p, fat: f, carb: c });
});
